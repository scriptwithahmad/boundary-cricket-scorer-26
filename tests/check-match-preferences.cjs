const assert = require('node:assert/strict');
const fs = require('node:fs');
const ts = require('typescript');
const mod = { exports: {} };
const source = ts.transpileModule(fs.readFileSync('src/store/preferences.ts', 'utf8'), { compilerOptions: { module: ts.ModuleKind.CommonJS } }).outputText;
new Function('exports', 'require', 'module', source)(mod.exports, require, mod);
const { normalizePreferences, defaultPreferences } = mod.exports;
assert.deepEqual(normalizePreferences(null), defaultPreferences);
const migrated = normalizePreferences({ keepScreenAwake: false, hapticVibration: false, playSound: true });
assert.equal(migrated.playSound, true);
assert.equal(migrated.keepScreenAwake, false);
assert.equal(migrated.recordShotDirections, true);
assert.equal(migrated.scoringLayout, 'auto');
const selected = { ...defaultPreferences, recordShotDirections: false, confirmWickets: false, boundaryCelebrations: false, milestoneAlerts: false, showPlayerStatistics: false, soundVolume: 0.25, scoringLayout: 'spacious' };
assert.deepEqual(normalizePreferences(JSON.parse(JSON.stringify(selected))), selected);
assert.equal(normalizePreferences({ soundVolume: -1 }).soundVolume, 0);
assert.equal(normalizePreferences({ soundVolume: 5 }).soundVolume, 1);
assert.equal(normalizePreferences({ soundVolume: NaN }).soundVolume, 1);
assert.deepEqual(normalizePreferences({ recordShotDirections: 'false', scoringLayout: 'invalid', soundVolume: 'loud' }), defaultPreferences);
console.log('Match preferences: migration, persistence, toggles, layouts and volume validation passed.');
