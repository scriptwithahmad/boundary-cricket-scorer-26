const assert = require('node:assert/strict');
const fs = require('node:fs');
const ts = require('typescript');
const source = fs.readFileSync('src/store/captains.ts', 'utf8');
const compiled = ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.CommonJS } }).outputText;
const mod = { exports: {} };
new Function('exports', 'require', 'module', compiled)(mod.exports, require, mod);
const { assignCaptains } = mod.exports;
const teams = [{ id: 'a' }, { id: 'b' }, { id: 'empty' }];
const players = [{ id: 'a1', teamId: 'a' }, { id: 'a2', teamId: 'a' }, { id: 'b1', teamId: 'b' }];
const data = assignCaptains({ teams, players, matches: [] });
assert.deepEqual(data.teams.map(t => t.captainId), ['a1', 'b1', undefined]);
const chosen = assignCaptains({ ...data, teams: data.teams.map(t => t.id === 'a' ? { ...t, captainId: 'a2' } : t) });
assert.equal(chosen.teams[0].captainId, 'a2');
assert.equal(assignCaptains(JSON.parse(JSON.stringify(chosen))).teams[0].captainId, 'a2');
assert.equal(assignCaptains({ ...chosen, players: players.filter(p => p.id !== 'a2') }).teams[0].captainId, 'a1');
assert.equal(assignCaptains({ ...data, teams: [{ id: 'a', captainId: 'b1' }] }).teams[0].captainId, 'a1');
assert.equal(assignCaptains({ ...data, players: [] }).teams[0].captainId, undefined);
assert.equal(assignCaptains({ teams: [{ id: 'a' }], players: [players[0]], matches: [] }).teams[0].captainId, 'a1');
assert.equal(teams[0].captainId, undefined);
console.log('Captain assignment, selection, persistence, removal and team isolation checks passed.');
